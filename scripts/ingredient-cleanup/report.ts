// Renders the cleanup plan as a Markdown review file.

import type { CleanupPlan, GroupPlan, SourcePlan, TargetRef } from "./plan";

const FLAG_LABELS: Record<string, string> = {
  brand: "brand name",
  "unclear-comma": "unclear text after a comma",
  placeholder: "not something you can buy",
  list: "a list of several ingredients",
};

export function renderReview(plan: CleanupPlan, unused: string[], snapshotDate: string): string {
  const byKey = new Map(plan.groups.map((group) => [group.key, group]));
  const nameOf = (ref: TargetRef) => byKey.get(ref.key)?.name ?? ref.key;
  const withNotes = (ref: TargetRef) => {
    const extras = [...ref.notes, ...(ref.unitHint ? [`unit: ${ref.unitHint}`] : [])];
    return extras.length > 0 ? `${nameOf(ref)} (notes: ${extras.join(", ")})` : nameOf(ref);
  };
  const of = (kind: SourcePlan["action"]["kind"]) => plan.sources.filter((source) => source.action.kind === kind);

  const merges = plan.groups.filter((group) => group.owners.length > 1);
  const renames = of("rename");
  const substitutes = of("substitutes");
  const splits = of("split");
  const created = plan.groups.filter((group) => group.created);
  const seeded = plan.groups.filter((group) => group.seedAliases.length > 0);
  const flagged = plan.sources.filter((source) => source.flags.length > 0);
  const unitChanges = plan.units.filter((unit) => unit.unit !== unit.raw || unit.notes.length > 0);
  // Groups made only of unused ingredients are deleted.
  const unusedNames = new Set(unused);
  const remaining = plan.groups.filter(
    (group) => group.created || !group.owners.every((owner) => unusedNames.has(owner))
  ).length;

  const sourceLine = (source: SourcePlan) => {
    const { action } = source;
    if (action.kind === "rename" || action.kind === "merge") return `\`${source.name}\` → ${withNotes(action.target)}`;
    if (action.kind === "substitutes")
      return `\`${source.name}\` → **${withNotes(action.target)}**, substitutes: ${action.substitutes.map(withNotes).join("; ")}`;
    if (action.kind === "split") return `\`${source.name}\` → ${action.items.map(withNotes).join(" + ")}`;
    return `\`${source.name}\``;
  };
  const mergeLine = (group: GroupPlan) => {
    const parts = group.owners.map((owner) => {
      const source = plan.sources.find((candidate) => candidate.name === owner)!;
      const action = source.action;
      const notes = "target" in action ? [...action.target.notes, ...(action.target.unitHint ? [`unit: ${action.target.unitHint}`] : [])] : [];
      return notes.length > 0 ? `\`${owner}\` (+ ${notes.join(", ")})` : `\`${owner}\``;
    });
    return `| **${group.name}** | ${parts.join(", ")} | \`${group.key}\` |`;
  };

  return [
    "# Ingredient cleanup: review",
    "",
    `Generated by \`npm run cleanup:review\` from the catalog as of ${snapshotDate}. Nothing has changed in the database yet.`,
    "",
    "**How to review:** read each section. To change something, edit `scripts/ingredient-cleanup/overrides.json` and run `npm run cleanup:review` again:",
    "",
    '- `"keep": ["name", …]` leaves those catalog names exactly as they are (no rename, merge or split).',
    '- `"names": { "<group key>": "new name" }` changes the name an ingredient ends up with (keys are in the merge table).',
    "",
    "Notes moved out of a name are added to the notes of every recipe row that used it, so nothing is lost.",
    "",
    "## Summary",
    "",
    `- ${plan.sources.length} ingredients today → about ${remaining} after the cleanup`,
    `- ${merges.length} merges, ${renames.length} renames, ${substitutes.length} "or" names split into substitutes, ${splits.length} names split into several ingredients`,
    `- ${created.length} ingredients created (options and list items not in the catalog yet)`,
    `- ${seeded.reduce((count, group) => count + group.seedAliases.length, 0)} seed synonyms recorded as aliases`,
    `- ${flagged.length} names flagged for a closer look, ${unitChanges.length} unit spellings changed, ${unused.length} unused ingredients deleted`,
    "",
    "## 1. Merges",
    "",
    "Each row becomes one ingredient. The most-used of the merged rows keeps its id; the others are deleted and their names become aliases, so they still resolve.",
    "",
    "| Becomes | From | Group key |",
    "|---|---|---|",
    ...merges.map(mergeLine),
    "",
    "## 2. Renames",
    "",
    ...renames.map((source) => `- ${sourceLine(source)}`),
    "",
    '## 3. "Or" names → ingredient + substitutes',
    "",
    "Every recipe row using one of these keeps the first option and gets a substitute row for each other option, with the same amount.",
    "",
    ...substitutes.map((source) => `- ${sourceLine(source)}`),
    "",
    "## 4. Split into several ingredients",
    "",
    "Lists don't keep the original amount on each item (it was for all of them together); it's added as a note. Staples like salt and pepper share it.",
    "",
    ...splits.map((source) => `- ${sourceLine(source)} *(${source.action.kind === "split" ? source.action.how : ""})*`),
    "",
    "## 5. Ingredients the cleanup creates",
    "",
    "Options and list items that aren't in the catalog yet. Each gets the category of the name it came from.",
    "",
    ...created.map((group) => `- **${group.name}** (from ${group.referencedBy.map((name) => `\`${name}\``).join(", ")})`),
    "",
    "## 6. Seed synonyms",
    "",
    ...seeded.map((group) => `- **${group.name}** ← ${group.seedAliases.map((alias) => `\`${alias}\``).join(", ")}`),
    "",
    "## 7. Needs a closer look",
    "",
    "Flagged by the naming rules. They're cleaned as shown above unless you add them to `keep`.",
    "",
    ...flagged.map((source) => `- ${sourceLine(source)}: ${source.flags.map((flag) => FLAG_LABELS[flag] ?? flag).join(", ")}`),
    "",
    "Made-in-recipe parts (to fix by hand, see plan 10j): `mandarin juice reduction`, `cooled mandarin juice reduction`, `blueberry chia jam`, `cream sauce base`, `avocado crema`, `spicy pulled pork filling`, `pulled pork filling`.",
    "",
    "## 8. Units",
    "",
    "| Written | Becomes | Moved to notes |",
    "|---|---|---|",
    ...unitChanges.map((unit) => {
      const moved = unit.sizeUnit
        ? `the quantity, as a size: "15 ${unit.raw}" → 1 ${unit.unit}, note "15 ${unit.sizeUnit}"`
        : unit.notes.join(", ");
      return `| \`${unit.raw}\` | ${unit.unit || "*(none)*"} | ${moved} |`;
    }),
    "",
    `Also: quantity, unit and notes written as \`null\`, \`none\` or \`n/a\` are cleared.`,
    "",
    "## 9. Deleted: unused ingredients",
    "",
    "No recipe uses these. Re-checked when the migration runs: anything a recipe or alias points at by then is kept.",
    "",
    ...unused.map((name) => `- \`${name}\``),
    "",
  ].join("\n");
}
