// Turns the approved cleanup plan into one data migration (step 7 of
// docs/ingredient-normalization.md). Pure: plan in, SQL out.
//
// Everything is matched by ingredient name (or name_key), never by id, so the
// migration does nothing on a fresh database. It runs as one transaction: if
// any check fails, nothing changes.

import { ingredientKey } from "../../src/features/ingredients/utils/ingredientKey";
import type { CleanupPlan, SourcePlan, TargetRef } from "./plan";

export type ApprovedPlan = CleanupPlan & { snapshotDate: string; unused: string[]; noAlias?: string[] };

const MISSING_WORDS = ["null", "none", "n/a", "na", "undefined", "nil", "-"];

const text = (value: string | null | undefined) => (value == null ? "null" : `'${value.replace(/'/g, "''")}'`);
const textArray = (values: string[]) =>
  values.length === 0 ? "'{}'::text[]" : `array[${values.map(text).join(", ")}]::text[]`;
const valuesInsert = (table: string, columns: string, rows: string[]) =>
  rows.length === 0 ? `-- (no ${table} rows)` : `insert into ${table} (${columns}) values\n  ${rows.join(",\n  ")};`;

type Owner = { name: string; key: string; notes: string[]; unitHint: string | null; alias: boolean };
type Extra = { name: string; kind: string; ord: number; target: TargetRef };

const ownerOf = (source: SourcePlan, key: string, noAlias: Set<string>): Owner => {
  const { action } = source;
  if (action.kind === "rename" || action.kind === "merge")
    return { name: source.name, key, ...pick(action.target), alias: !noAlias.has(source.name) };
  if (action.kind === "substitutes") return { name: source.name, key, ...pick(action.target), alias: false };
  return { name: source.name, key, notes: [], unitHint: null, alias: false };
};
const pick = (target: TargetRef) => ({ notes: target.notes, unitHint: target.unitHint });

const extrasOf = (source: SourcePlan): Extra[] => {
  const { action } = source;
  if (action.kind === "substitutes")
    return action.substitutes.map((target, index) => ({ name: source.name, kind: "substitute", ord: index + 1, target }));
  if (action.kind === "split")
    return action.items.map((target, index) => ({ name: source.name, kind: action.how, ord: index, target }));
  return [];
};

export function renderCleanupMigration(plan: ApprovedPlan, seedAliases: Record<string, string[]>): string {
  const sourceByName = new Map(plan.sources.map((source) => [source.name, source]));
  const noAlias = new Set(plan.noAlias ?? []);

  const groups = plan.groups.map((group) => `(${text(group.key)}, ${text(group.name)})`);
  const owners = plan.groups.flatMap((group) =>
    group.owners.map((name) => {
      const owner = ownerOf(sourceByName.get(name)!, group.key, noAlias);
      return `(${text(owner.name)}, ${text(owner.key)}, ${text(ingredientKey(owner.name))}, ${textArray(owner.notes)}, ${text(owner.unitHint)}, ${owner.alias})`;
    })
  );
  const extras = plan.sources.flatMap(extrasOf).map(
    (extra) =>
      `(${text(extra.name)}, ${text(extra.kind)}, ${extra.ord}, ${text(extra.target.key)}, ${textArray(extra.target.notes)}, ${text(extra.target.unitHint)})`
  );
  const units = plan.units
    .filter((unit) => unit.unit !== unit.raw || unit.notes.length > 0 || unit.sizeUnit)
    .map((unit) => `(${text(unit.raw)}, ${text(unit.unit)}, ${textArray(unit.notes)}, ${text(unit.sizeUnit ?? null)})`);
  const seeds = new Map<string, string>();
  for (const [canonical, variants] of Object.entries(seedAliases))
    for (const variant of variants) {
      const aliasKey = ingredientKey(variant);
      if (!seeds.has(aliasKey)) seeds.set(aliasKey, `(${text(aliasKey)}, ${text(variant)}, ${text(ingredientKey(canonical))})`);
    }
  const unused = plan.unused.map((name) => `(${text(name)})`);
  const missing = MISSING_WORDS.map(text).join(", ");

  return `-- Ingredient catalog cleanup (step 7 of docs/ingredient-normalization.md).
-- Generated by \`npm run cleanup:migration\` from scripts/ingredient-cleanup/plan.json
-- (catalog snapshot ${plan.snapshotDate}); the reviewed plan is
-- scripts/ingredient-cleanup/review.md. Do not edit by hand.
--
-- Merges duplicate ingredients, moves size/prep words from names into recipe
-- notes, splits "or" names into substitutes and lists into separate rows,
-- normalizes unit spellings, records aliases, and deletes unused ingredients.
-- Rows are matched by name or name_key, never by id, so this does nothing on
-- a fresh database. Any failed check aborts the whole migration.

-- 1. The approved plan --------------------------------------------------------

create temp table cleanup_group (key text primary key, name text not null);
create temp table cleanup_owner (
  name text primary key, key text not null, old_key text not null,
  notes text[] not null, unit_hint text, alias boolean not null
);
create temp table cleanup_extra (
  name text not null, kind text not null, ord int not null,
  key text not null, notes text[] not null, unit_hint text
);
create temp table cleanup_unit (raw text primary key, unit text not null, notes text[] not null, size_unit text);
create temp table cleanup_seed (alias_key text primary key, alias_name text not null, key text not null);
create temp table cleanup_unused (name text primary key);

${valuesInsert("cleanup_group", "key, name", groups)}

${valuesInsert("cleanup_owner", "name, key, old_key, notes, unit_hint, alias", owners)}

${valuesInsert("cleanup_extra", "name, kind, ord, key, notes, unit_hint", extras)}

${valuesInsert("cleanup_unit", "raw, unit, notes, size_unit", units)}

${valuesInsert("cleanup_seed", "alias_key, alias_name, key", [...seeds.values()])}

${valuesInsert("cleanup_unused", "name", unused)}

-- Same rule as joinNotes in src/lib/utils/text.ts: ", "-joined, empties and
-- case-insensitive repeats dropped, first-seen order kept.
create function pg_temp.join_notes(parts text[]) returns text
language sql immutable as $$
  select nullif(string_agg(part, ', ' order by first_at), '')
  from (
    select distinct on (lower(part)) part, ord as first_at
    from (
      select btrim(regexp_replace(p, '\\s+', ' ', 'g')) as part, ord
      from unnest(parts) with ordinality as u(p, ord)
      where p is not null
    ) cleaned
    where part <> '' and lower(part) not in (${missing})
    order by lower(part), ord
  ) kept
$$;

-- Unused ingredients, by id, before any renaming.
create temp table cleanup_unused_id as
select i.id from public.ingredients i join cleanup_unused u on u.name = i.name;

-- 2. Missing-value text and unit spellings ------------------------------------

update public.recipe_ingredients set
  quantity = case when lower(btrim(quantity)) in (${missing}) then null else quantity end,
  unit = case when lower(btrim(unit)) in (${missing}) then null else unit end,
  notes = case when lower(btrim(notes)) in (${missing}) then null else notes end
where lower(btrim(quantity)) in (${missing})
   or lower(btrim(unit)) in (${missing})
   or lower(btrim(notes)) in (${missing});

-- "15" + "ounce can" is one 15 oz can, not 15 cans.
update public.recipe_ingredients r set
  unit = nullif(u.unit, ''),
  quantity = case when u.size_unit is not null and nullif(btrim(r.quantity), '') is not null then '1' else r.quantity end,
  quantity_numeric = case when u.size_unit is not null and nullif(btrim(r.quantity), '') is not null then 1 else r.quantity_numeric end,
  notes = pg_temp.join_notes(
    case when u.size_unit is not null and nullif(btrim(r.quantity), '') is not null
      then array[btrim(r.quantity) || ' ' || u.size_unit] else '{}'::text[] end
    || u.notes || array[r.notes])
from cleanup_unit u
where r.unit = u.raw;

-- 3. Which ingredient each group keeps ----------------------------------------

-- Every ingredient that belongs to a group: by name from the plan, and by
-- name_key for ingredients added after the snapshot.
create temp table cleanup_map as
select i.id, i.name, i.category, o.key, o.old_key, o.notes, o.unit_hint, o.alias
from public.ingredients i join cleanup_owner o on o.name = i.name;

insert into cleanup_map
select i.id, i.name, i.category, g.key, g.key, '{}'::text[], null, false
from public.ingredients i join cleanup_group g on g.key = i.name_key
where not exists (select 1 from cleanup_map m where m.id = i.id)
  and not exists (select 1 from cleanup_extra e where e.name = i.name);

-- Ingredients split into several ("salt and pepper") go away entirely.
create temp table cleanup_split_source as
select distinct i.id, i.name, i.category
from public.ingredients i join cleanup_extra e on e.name = i.name
where e.kind <> 'substitute';

-- The most-used ingredient of each group keeps its row and id.
create temp table cleanup_keeper as
select distinct on (m.key) m.key, m.id
from cleanup_map m join cleanup_group g on g.key = m.key
order by m.key,
  (select count(*) from public.recipe_ingredients r where r.ingredient_id = m.id) desc,
  (m.name = g.name) desc,
  m.id;

-- Free every name the cleanup is about to use: everything that isn't a keeper
-- already called its final name gets a temporary one.
update public.ingredients i set name = '~cleanup~' || i.id
where i.id in (select id from cleanup_split_source)
   or (i.id in (select id from cleanup_map)
       and not exists (
         select 1 from cleanup_keeper k join cleanup_group g on g.key = k.key
         where k.id = i.id and g.name = i.name));

-- Options and list items not in the catalog yet, if something points at them.
-- They take the category of the name they came from.
with created as (
  insert into public.ingredients (name, name_key, category)
  select g.name, g.key, (
    select s.category
    from cleanup_extra e
    join (select id, name, category from cleanup_map union all select id, name, category from cleanup_split_source) s
      on s.name = e.name
    where e.key = g.key
    order by s.category is null, s.category = 'other', s.name
    limit 1)
  from cleanup_group g
  where not exists (select 1 from cleanup_keeper k where k.key = g.key)
    and exists (
      select 1 from cleanup_extra e
      join (select name from cleanup_map union all select name from cleanup_split_source) s on s.name = e.name
      where e.key = g.key)
  returning id, name_key
)
insert into cleanup_keeper select name_key, id from created;

-- A keeper with no category (or "other") takes one from the rows merged into it.
update public.ingredients i set category = (
  select m.category from cleanup_map m
  where m.key = k.key and m.category is not null and m.category <> 'other'
  group by m.category order by count(*) desc, m.category limit 1)
from cleanup_keeper k
where i.id = k.id
  and (i.category is null or i.category = 'other')
  and exists (
    select 1 from cleanup_map m
    where m.key = k.key and m.category is not null and m.category <> 'other');

-- 4. Recipe rows --------------------------------------------------------------

-- Recipe rows that gain substitute or split rows, as they are now.
create temp table cleanup_source_row as
select r.id, r.recipe_id, r.quantity, r.quantity_numeric, r.unit, r.notes, r.position, r.substitute_for,
       coalesce(m.name, s.name) as source_name
from public.recipe_ingredients r
left join cleanup_map m on m.id = r.ingredient_id
left join cleanup_split_source s on s.id = r.ingredient_id
where s.id is not null
   or exists (select 1 from cleanup_extra e where e.name = m.name);

-- Leave room after each of those rows for what's added: positions x10.
update public.recipe_ingredients set position = position * 10
where recipe_id in (select recipe_id from cleanup_source_row);

-- Rows on a merged or renamed ingredient: point at the keeper, add the words
-- moved out of the name to the notes, and use the name's unit ("garlic
-- cloves" → clove) when the row has an amount but no unit.
update public.recipe_ingredients r set
  ingredient_id = k.id,
  ingredient_name = g.name,
  notes = pg_temp.join_notes(m.notes || array[r.notes]),
  unit = case when m.unit_hint is not null and nullif(btrim(r.unit), '') is null
              and nullif(btrim(r.quantity), '') is not null then m.unit_hint else r.unit end
from cleanup_map m
join cleanup_keeper k on k.key = m.key
join cleanup_group g on g.key = m.key
where r.ingredient_id = m.id;

-- "olive or grapeseed oil": a substitute row per option, same amount.
insert into public.recipe_ingredients
  (recipe_id, ingredient_id, ingredient_name, quantity, quantity_numeric, unit, notes, position, substitute_for)
select s.recipe_id, k.id, g.name, s.quantity, s.quantity_numeric,
       case when e.unit_hint is not null and nullif(btrim(s.unit), '') is null
            and nullif(btrim(s.quantity), '') is not null then e.unit_hint else s.unit end,
       pg_temp.join_notes(e.notes), s.position * 10 + e.ord, coalesce(s.substitute_for, s.id)
from cleanup_source_row s
join cleanup_extra e on e.name = s.source_name and e.kind = 'substitute'
join cleanup_keeper k on k.key = e.key
join cleanup_group g on g.key = e.key;

-- Split names: the first item takes over the row, the others are added after
-- it. Staples ("salt and pepper") share the amount; list items get it as a
-- note, since it was for all of them together.
create temp table cleanup_split_row as
select s.*, e.kind, e.ord, e.notes as item_notes, e.unit_hint, k.id as ingredient_id, g.name as ingredient_name,
       nullif(btrim(concat_ws(' ', btrim(s.quantity), btrim(s.unit))), '') as amount
from cleanup_source_row s
join cleanup_extra e on e.name = s.source_name and e.kind <> 'substitute'
join cleanup_keeper k on k.key = e.key
join cleanup_group g on g.key = e.key;

update public.recipe_ingredients r set
  ingredient_id = x.ingredient_id,
  ingredient_name = x.ingredient_name,
  quantity = case when x.kind = 'list' then null else r.quantity end,
  quantity_numeric = case when x.kind = 'list' then null else r.quantity_numeric end,
  unit = case when x.kind = 'list' then null else r.unit end,
  notes = pg_temp.join_notes(
    case when x.kind = 'list' then array[x.amount] else '{}'::text[] end || x.item_notes || array[r.notes])
from cleanup_split_row x
where x.ord = 0 and r.id = x.id;

insert into public.recipe_ingredients
  (recipe_id, ingredient_id, ingredient_name, quantity, quantity_numeric, unit, notes, position, substitute_for)
select x.recipe_id, x.ingredient_id, x.ingredient_name,
       case when x.kind = 'list' then null else x.quantity end,
       case when x.kind = 'list' then null else x.quantity_numeric end,
       case when x.kind = 'list' then null else x.unit end,
       pg_temp.join_notes(case when x.kind = 'list' then array[x.amount] else '{}'::text[] end || x.item_notes),
       x.position * 10 + x.ord, x.substitute_for
from cleanup_split_row x
where x.ord > 0;

-- Back to 0, 1, 2, … in each recipe that changed.
update public.recipe_ingredients r set position = ordered.position
from (
  select id, (row_number() over (partition by recipe_id order by position, created_at, id) - 1)::smallint as position
  from public.recipe_ingredients
  where recipe_id in (select recipe_id from cleanup_source_row)
) ordered
where r.id = ordered.id;

-- 5. Catalog ------------------------------------------------------------------

-- Aliases on merged-away ingredients move to the keeper.
update public.ingredient_aliases a set ingredient_id = k.id
from cleanup_map m join cleanup_keeper k on k.key = m.key
where a.ingredient_id = m.id and m.id <> k.id;

-- Merged-away and split ingredients. Nothing points at them any more; if
-- something still does, the foreign key stops the migration.
delete from public.ingredients i
using cleanup_map m join cleanup_keeper k on k.key = m.key
where i.id = m.id and m.id <> k.id;

delete from public.ingredients i using cleanup_split_source s where i.id = s.id;

-- Unused ingredients, re-checked now: anything a recipe or alias points at stays.
delete from public.ingredients i
using cleanup_unused_id u
where i.id = u.id
  and not exists (select 1 from public.recipe_ingredients r where r.ingredient_id = i.id)
  and not exists (select 1 from public.ingredient_aliases a where a.ingredient_id = i.id);

-- Keepers take the group's name and key.
update public.ingredients i set name = g.name, name_key = g.key
from cleanup_keeper k join cleanup_group g on g.key = k.key
where i.id = k.id;

-- Seed synonyms ("scallions" → green onion), then the names merged away, so
-- they still resolve. A key that is already an ingredient's own key is skipped.
insert into public.ingredient_aliases (alias_key, alias_name, ingredient_id, source, status)
select s.alias_key, s.alias_name, i.id, 'seed', 'approved'
from cleanup_seed s
join cleanup_keeper k on k.key = s.key
join public.ingredients i on i.id = k.id
where not exists (select 1 from public.ingredients other where other.name_key = s.alias_key)
on conflict (alias_key) do nothing;

insert into public.ingredient_aliases (alias_key, alias_name, ingredient_id, source, status)
select distinct on (m.old_key) m.old_key, m.name, i.id, 'merge', 'approved'
from cleanup_map m
join cleanup_keeper k on k.key = m.key
join public.ingredients i on i.id = k.id
where m.alias
  and m.old_key <> m.key
  and not exists (select 1 from public.ingredients other where other.name_key = m.old_key)
order by m.old_key, m.name
on conflict (alias_key) do nothing;

-- 6. Checks -------------------------------------------------------------------

do $$
declare
  duplicate_keys text;
begin
  if exists (select 1 from public.ingredients where name like '~cleanup~%') then
    raise exception 'ingredient cleanup: an ingredient was left with a temporary name';
  end if;
  select string_agg(name_key, ', ') into duplicate_keys
  from (select name_key from public.ingredients where name_key is not null group by name_key having count(*) > 1) d;
  if duplicate_keys is not null then
    raise exception 'ingredient cleanup: several ingredients share a key: %', duplicate_keys;
  end if;
end $$;

drop function pg_temp.join_notes(text[]);
drop table cleanup_group, cleanup_owner, cleanup_extra, cleanup_unit, cleanup_seed, cleanup_unused,
  cleanup_unused_id, cleanup_map, cleanup_split_source, cleanup_keeper, cleanup_source_row, cleanup_split_row;
`;
}
